    public string Language { get; private set; } = DefaultLanguage;

    public event Action? OnChange;

    public string T(string key)
    {
        if (_strings.TryGetValue(Language, out var languageStrings) && languageStrings.TryGetValue(key, out var value))
        {
            return value;
        }

        if (_strings.TryGetValue(DefaultLanguage, out var defaultStrings) && defaultStrings.TryGetValue(key, out var fallback))
        {
            return fallback;
        }

        return key;
    }

    public async Task InitializeAsync(IJSRuntime jsRuntime)
    {
        if (_initialized)
        {
            return;
        }

        _initialized = true;
        var stored = await jsRuntime.InvokeAsync<string>("comunaclic.getLang");
        if (!string.IsNullOrWhiteSpace(stored) && SupportedLanguages.Contains(stored))
        {
            Language = stored.ToLowerInvariant();
            OnChange?.Invoke();
        }
    }

    public async Task SetLanguageAsync(string language, IJSRuntime jsRuntime)
    {
        if (!SupportedLanguages.Contains(language))
        {
            return;
        }

        if (string.Equals(Language, language, StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        Language = language.ToLowerInvariant();
        await jsRuntime.InvokeVoidAsync("comunaclic.setLang", Language);
        OnChange?.Invoke();
    }
